"""Render launcher vectors into grayscale spans for the native control centre."""
from io import BytesIO
from itertools import groupby
from pathlib import Path
import xml.etree.ElementTree as ET

from cairosvg import svg2png
from PIL import Image

base = Path(__file__).resolve().parent
android = "{http://schemas.android.com/apk/res/android}"
icons = {"wifi": (40, 64), "refresh": (64,), "flash": (64,),
         "rotate": (64,), "exit": (64,), "sun": (40,), "moon": (64,), "usb": (64,), "broom": (64,)}


def svg_color(value):
    if len(value) == 9:
        return ("#" + value[3:]) if value[1:3].lower() == "ff" else "none"
    return value


def render(name, size):
    vector = ET.parse(base.parent / f"launcher/res/drawable/ic_{name}.xml").getroot()
    assert vector.get(android + "viewportWidth") == vector.get(android + "viewportHeight") == "24"
    svg = ET.Element("svg", xmlns="http://www.w3.org/2000/svg", viewBox="0 0 24 24")
    attrs = {"pathData": "d", "strokeColor": "stroke", "strokeWidth": "stroke-width",
             "strokeLineCap": "stroke-linecap", "strokeLineJoin": "stroke-linejoin", "fillColor": "fill"}
    for path in vector:
        assert path.tag == "path"
        assert all(key.removeprefix(android) in attrs for key in path.attrib), name
        ET.SubElement(svg, "path", {
            target: svg_color(value) if key.endswith("Color") else value
            for key, target in attrs.items() if (value := path.get(android + key)) is not None
        })
    pixels = Image.open(BytesIO(svg2png(bytestring=ET.tostring(svg), output_width=size, output_height=size)))
    alpha = pixels.convert("RGBA").getchannel("A")
    for y in range(size):
        x = 0
        for level, group in groupby(alpha.crop((0, y, size, y + 1)).getdata(),
                                    key=lambda v: round(v * 4 / 255)):
            length = len(list(group))
            if level:
                yield f"{{{x},{y},{length},{level}}}"
            x += length


lines = ["/* Generated by make-panel-icons.py from launcher/res/drawable. */",
         "struct icon_span { uint8_t x, y, width, coverage; };"]
for name, sizes in icons.items():
    for size in sizes:
        spans = list(render(name, size))
        lines.append(f"static const struct icon_span icon_{name}_{size}[] = {{")
        lines.extend("    " + ",".join(spans[i:i + 8]) + "," for i in range(0, len(spans), 8))
        lines.append("};")
(base / "panel-icons.h").write_text("\n".join(lines) + "\n")
