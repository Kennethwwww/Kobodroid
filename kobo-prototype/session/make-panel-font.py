"""Generate panel-font.h: 1-bit bitmaps of exactly the characters the Kobo panel draws.
Adapted from android7-prototype/display/tools/make-panel-font.py. Every ZH("...") literal in session-ui.h is
scanned, plus digits and '%:.' (values drawn at run time), and rasterized from Noto Sans CJK SC Regular
(SIL Open Font License 1.1, the font Android ships), read from the Android 7 system image.
  python3 make-panel-font.py ../build/font/NotoSansCJK-Regular.ttc"""
import hashlib, re, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SRC = HERE / 'session-ui.h'
OUT = HERE / 'panel-font.h'
FONT = Path(sys.argv[1])
SIZES = (40, 30, 80)  # FONT_L (panel labels, buttons), FONT_S (status bar, values), FONT_XL (loading title)
SC_INDEX = 2      # face index of "Noto Sans CJK SC" in the collection

chars = set('0123456789%:.')
for lit in re.findall(r'ZH\("((?:[^"\\]|\\.)*)"\)', SRC.read_text(encoding='utf-8')):
    chars.update(lit)
chars = sorted(chars)

glyphs, bits, heights, digit_centers = [], bytearray(), [], []
for cls, size in enumerate(SIZES):
    font = ImageFont.truetype(str(FONT), size, index=SC_INDEX)
    assert font.getname()[0] == 'Noto Sans CJK SC', font.getname()
    ascent, descent = font.getmetrics()
    h = ascent + descent
    heights.append(h)
    for ch in chars:
        w = max(1, round(font.getlength(ch)))
        img = Image.new('L', (w, h), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255, anchor='la')
        if ch == '0':
            _, top, _, bottom = img.point(lambda value: 255 if value >= 128 else 0).getbbox()
            digit_centers.append((top + bottom) // 2)
        px = img.load()
        off = len(bits)
        stride = (w + 7) // 8
        for y in range(h):
            row = bytearray(stride)
            for x in range(w):
                if px[x, y] >= 128:
                    row[x // 8] |= 0x80 >> (x % 8)
            bits += row
        glyphs.append((ord(ch), cls, w, off))

lines = ['/* Generated by make-panel-font.py from %s (sha256 %s), Noto Sans CJK SC Regular,' % (FONT.name, hashlib.sha256(FONT.read_bytes()).hexdigest()[:16]),
         ' * SIL Open Font License 1.1. Do not edit. Characters: %s */' % ''.join(c for c in chars if c != '*'),
         '#include <stdint.h>',
         'struct kd_glyph { uint32_t cp; uint8_t cls; uint8_t w; uint32_t off; };  /* rows of ceil(w/8) bytes, MSB first */',
         'static const int kd_glyph_h[%d] = {%s};' % (len(SIZES), ', '.join(map(str, heights))),
         'static const int kd_digit_center_y[%d] = {%s};' % (len(SIZES), ', '.join(map(str, digit_centers))),
         'static const struct kd_glyph kd_glyphs[%d] = {' % len(glyphs)]
lines += ['  {0x%04x, %d, %d, %d},' % g for g in glyphs]
lines += ['};', 'static const unsigned char kd_glyph_bits[%d] = {' % len(bits)]
for i in range(0, len(bits), 24):
    lines.append('  ' + ','.join(str(b) for b in bits[i:i + 24]) + ',')
lines += ['};', '']
OUT.write_text('\n'.join(lines))
print('PANEL_FONT glyphs=%d bytes=%d' % (len(glyphs), len(bits)))
